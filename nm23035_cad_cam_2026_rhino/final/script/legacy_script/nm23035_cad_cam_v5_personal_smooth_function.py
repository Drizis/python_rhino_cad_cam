def get_bending_energy(nurbs, samples):
    domain = nurbs.Domain 
    step = domain.Length / samples 
    total_E2 = 0
    total_E3 = 0

    for i in range(samples):
        t1 = domain.Min + (i * step)
        t2 = domain.Min + ((i + 1) * step)
        
        p1 = nurbs.PointAt(t1)
        p2 = nurbs.PointAt(t2)
        ds = p1.DistanceTo(p2)
        
        k1 = nurbs.CurvatureAt(t1).Length
        k2 = nurbs.CurvatureAt(t2).Length
        total_E2 += ((k1**2 + k2**2) / 2.0) * ds
        
        der1 = nurbs.DerivativeAt(t1, 3)[3].SquareLength
        der2 = nurbs.DerivativeAt(t2, 3)[3].SquareLength
        total_E3 += ((der1 + der2) / 2.0) * ds
        
    return total_E2, total_E3

def get_ranking_numbers(nurbs, alpha=1.0, beta=0.1):
    knots = nurbs.Knots
    degree = nurbs.Degree
    cp_count = len(nurbs.Points)
    ranking_list = []

    for i in range(2, cp_count - 2):
        # Ελέγχουμε αν το σημείο είναι "ελεύθερο" (όχι κλειδωμένο σε ευθεία)
        # Αν το σημείο είναι πάνω στο FOB ή FOS, το αγνοούμε από το ranking 
        # για να μην ανακυκλώνουμε ενέργεια που δεν μπορεί να αλλάξει.
        t_start = knots[i]
        t_end = knots[i + degree + 1]
        
        e2_l, e3_l = get_local_energy(nurbs, t_start, t_end, 15)
        z_i = (alpha * e2_l) + (beta * e3_l)
        ranking_list.append((i, z_i))
    
    ranking_list.sort(key=lambda x: x[1], reverse=True)
    return ranking_list

def get_local_energy(nurbs, t_min, t_max, samples):
    """Βοηθητική συνάρτηση για υπολογισμό ενέργειας σε συγκεκριμένο διάστημα [t_min, t_max]"""
    step = (t_max - t_min) / samples
    e2 = 0
    e3 = 0
    
    for j in range(samples):
        t1 = t_min + (j * step)
        t2 = t_min + ((j + 1) * step)
        
        p1 = nurbs.PointAt(t1)
        p2 = nurbs.PointAt(t2)
        ds = p1.DistanceTo(p2)
        
        #E2
        k1 = nurbs.CurvatureAt(t1).Length
        k2 = nurbs.CurvatureAt(t2).Length
        e2 += ((k1**2 + k2**2) / 2.0) * ds
        
        #E3
        der1 = nurbs.DerivativeAt(t1, 3)[3].SquareLength
        der2 = nurbs.DerivativeAt(t2, 3)[3].SquareLength
        e3 += ((der1 + der2) / 2.0) * ds
        
    return e2, e3

def apply_delta_constraint(original_pos, target_pos, delta):
    vector = target_pos - original_pos
    if vector.Length <= delta: return target_pos
    vector.Unitize()
    return original_pos + (vector * delta)

def apply_hull_constraints(point, limits, tol=0.001):
    nx, ny, nz = point.X, point.Y, point.Z
    if nz <= limits["z_min"] + tol: nz = limits["z_min"]
    if ny >= limits["y_max"] - tol: ny = limits["y_max"]
    if ny <= limits["y_min"] + tol: ny = limits["y_min"]
    if nz > limits["z_max"]: nz = limits["z_max"]
    if nx < limits["x_min"]: nx = limits["x_min"]
    return rg.Point3d(nx, ny, nz)

def straighten_limit_segments(pts, limits, tol=0.001):
    # FOS straightening
    fos_idx = [i for i, p in enumerate(pts) if abs(p.Y - limits["y_max"]) < tol]
    if len(fos_idx) >= 2:
        for i in range(min(fos_idx), max(fos_idx) + 1):
            pts[i] = rg.Point3d(pts[i].X, limits["y_max"], pts[i].Z)
    # FOB straightening
    fob_idx = [i for i, p in enumerate(pts) if abs(p.Z - limits["z_min"]) < tol]
    if len(fob_idx) >= 2:
        for i in range(min(fob_idx), max(fob_idx) + 1):
            pts[i] = rg.Point3d(pts[i].X, pts[i].Y, limits["z_min"])
    return pts

def get_inflection_points(curve_id, samples, plane_vector):
    """
    με αυτή τη συνάρτηση θα βρίσκω πόσες φορές αλλάζει το πρόσημο της καμπυλότητας μιας
    καμπύλης, δλδ θα βρίσκουμε το πλήθος των σημείων καμπης
    για να δουμε εαν υπάρχει σημείο καμπής θα εξετάζουμε εάν το εσωτερικό γινόμενο
    του εξωτερικου γινομένου (της εφαπτομένης με την καμπυλότητα) και του διανύσματος του επιπέδου
    που ανήκει η καμπύλη διατηρεί σταθερό πρόσημο, άθε αλλαγή προσήμου σημαίνει πως υπάρχει σημείο καμπής
    του οποίου οι συντεταγμένες αποθηκεύονται
    for profile => XZ plane => plane_vector = (0,1,0)
    """
    ref_normal = rg.Vector3d(*plane_vector)
    curve = rs.coercecurve(curve_id)
    if not curve: return []
    domain = curve.Domain
    length = domain.Length
    step = length / samples
    inflection_points = []
    prev_sign = 0 

    for i in range(samples + 1):
        t = domain.Min + (i *step)
        tangent = curve.TangentAt(t)
        curr_vec = curve.CurvatureAt(t)
        if curr_vec.Length > 0.000001: #ελέγχω πως δεν είναι ευθεία με καμπυλότητα 0
            cp = rg.Vector3d.CrossProduct(tangent, curr_vec)
            dot_product = cp * ref_normal
            if dot_product > 0: curr_sign = 1
            else: curr_sign = -1
            if prev_sign != 0 and prev_sign != curr_sign:
                point = curve.PointAt(t)
                inflection_points.append(point)
            prev_sign = curr_sign
    return inflection_points

def get_hull_limits(b_half, d_total, profile_pts):
    """
    Ορίζει τα γεωμετρικά όρια της γάστρας
    """
    #βρίσκω τη θέση του Transom
    x_transom = min(rs.coerce3dpoint(p)[0] for p in profile_pts)
    limits = {
        "x_min": x_transom,       #Transom Limit
        "x_max": None,            #Bow Limit
        "y_min": 0,               #Profile
        "y_max": b_half,          #FOS
        "z_min": 0,               #FOB
        "z_max": d_total          #Deck
    }
    return limits

def run_automatic_fairing(curve_id, limits, delta, iterations=1000):
    nurbs = rs.coercecurve(curve_id).ToNurbsCurve()
    # Κρατάμε τα σημεία ΜΕΤΑ το rebuild ως βάση για το delta
    orig_pts = [rg.Point3d(nurbs.Points[i].Location) for i in range(len(nurbs.Points))]
    
    print("\n" + "="*40)
    print("STARTING SUPER-FAIRING: DELTA = {}".format(delta))

    for cycle in range(iterations):
        ranking = get_ranking_numbers(nurbs)
        if not ranking: break
        
        moved_count = 0
        # Δοκιμάζουμε να κουνήσουμε τα σημεία από τη λίστα ranking
        for k in range(len(ranking)):
            idx_r, z_r = ranking[k]
            
            current_pos = rg.Point3d(nurbs.Points[idx_r].Location)
            prev_pos = nurbs.Points[idx_r-1].Location
            next_pos = nurbs.Points[idx_r+1].Location
            
            # --- BOOSTED SMOOTHING (Over-relaxation) ---
            # Αντί για σκέτο μέσο όρο, σπρώχνουμε πιο δυνατά προς την εξομάλυνση
            target = (prev_pos + next_pos) / 2.0
            move_vector = target - current_pos
            # Σπρώχνουμε το σημείο στο 80% της διαδρομής προς το ιδανικό
            target_boosted = current_pos + (move_vector * 0.8) 
            
            # 1. Apply Delta Constraint (Απόσταση από το REBUILT σημείο)
            new_pos = apply_delta_constraint(orig_pts[idx_r], target_boosted, delta)
            
            # 2. Apply Hull Limits (FOB, FOS)
            new_pos = apply_hull_constraints(new_pos, limits)
            
            # Ελέγχουμε αν το σημείο όντως κουνήθηκε
            if current_pos.DistanceTo(new_pos) > 0.001:
                nurbs.Points.SetPoint(idx_r, new_pos)
                moved_count += 1
            
            # Κουνάμε έως 10 σημεία ανά κύκλο για ταχύτητα
            if moved_count >= 10: break 

        # Κάθε 50 κύκλους κάνουμε ένα "Deep Straighten" στα όρια
        if cycle % 50 == 0:
            pts_list = [nurbs.Points[i].Location for i in range(len(nurbs.Points))]
            pts_list = straighten_limit_segments(pts_list, limits)
            for i, p in enumerate(pts_list): nurbs.Points.SetPoint(i, p)
            
            e2, e3 = get_bending_energy(nurbs, 1000)
            print("Cycle {:4d} | E2: {:10.2f} | E3: {:10.2e}".format(cycle, e2, e3))
            Rhino.RhinoDoc.ActiveDoc.Objects.Replace(curve_id, nurbs)
            rs.Redraw()

    Rhino.RhinoDoc.ActiveDoc.Objects.Replace(curve_id, nurbs)
    rs.Redraw()
    print("FAIRING COMPLETE.")



